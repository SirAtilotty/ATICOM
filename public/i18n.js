// Tarayıcı depolaması kapalıysa uygulama varsayılan dille çalışmaya devam eder.
let lang = 'en';
try {
  if (localStorage.getItem('aticom-lang') === 'tr') lang = 'tr';
} catch {}

function setLang(next) {
  lang = next;
  try {
    localStorage.setItem('aticom-lang', next);
  } catch {}
}

function t(key, vars = {}) {
  const text = I18N[lang][key] ?? I18N[lang]['err.serverError'];
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name]);
}

const locale = () => (lang === 'tr' ? 'tr-TR' : 'en-GB');

function translatePage() {
  document.documentElement.lang = lang;
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of document.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of document.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}
